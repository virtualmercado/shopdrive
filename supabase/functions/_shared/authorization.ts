// Shared authorization helpers for privileged edge functions.
// Pure functions only (no Deno/npm imports) so they can be unit-tested
// from the frontend test suite and reused by every function.

export interface CallerContext {
  /** Authenticated user id (JWT sub). Null for anon-key/guest callers. */
  userId: string | null;
  /** True when the caller holds the Master/admin role (validated server-side). */
  isAdmin: boolean;
}

/** Extract the Bearer token from the Authorization header, or null. */
export function extractBearerToken(req: Request): string | null {
  const header = req.headers.get("authorization") ?? req.headers.get("Authorization");
  if (!header || !header.startsWith("Bearer ")) return null;
  const token = header.slice("Bearer ".length).trim();
  return token.length > 0 ? token : null;
}

/** Internal job tokens are 64-char hex strings generated by the database. */
export function isValidJobTokenFormat(token: string): boolean {
  return /^[0-9a-f]{64}$/.test(token);
}

/**
 * Media delete policy (fail-closed):
 * - products/{product_id}/... -> only the product owner or a Master/admin;
 * - any other prefix -> rejected (no generic bucket deletes).
 */
export function mediaDeleteDecision(
  objectKey: string,
  caller: CallerContext,
  productOwnerId: string | null,
): "allow" | "deny" {
  const parts = objectKey.split("/");
  if (parts[0] === "products" && parts[1]) {
    if (caller.isAdmin) return "allow";
    if (caller.userId && productOwnerId && caller.userId === productOwnerId) return "allow";
    return "deny";
  }
  return "deny";
}

/**
 * PIX status-check policy:
 * - Master/admin, the store owner and the customer who placed the order: allowed;
 * - anonymous/guest callers (no user id): allowed, because guest checkout polling
 *   must keep working and every write is derived from the gateway response,
 *   never from caller input;
 * - any other authenticated user: denied (cross-tenant).
 */
export function canAccessPixPayment(
  caller: CallerContext,
  payment: { store_owner_id: string },
  order: { customer_id: string | null } | null,
): boolean {
  if (caller.isAdmin) return true;
  if (!caller.userId) return true; // guest checkout polling; writes are gateway-derived
  if (caller.userId === payment.store_owner_id) return true;
  if (order?.customer_id && caller.userId === order.customer_id) return true;
  return false;
}

export interface OrderItemRow {
  product_name: string;
  quantity: number;
  product_price: number;
}

export interface CheckoutItem {
  name: string;
  quantity: number;
  price: number; // cents
}

/**
 * Build InfinitePay checkout items exclusively from persisted order items.
 * Client-supplied items/prices are never accepted.
 */
export function buildCheckoutItemsFromOrder(items: OrderItemRow[]): CheckoutItem[] {
  return items.map((it) => ({
    name: String(it.product_name).slice(0, 100),
    quantity: Math.max(1, Math.floor(Number(it.quantity) || 1)),
    price: Math.round(Number(it.product_price) * 100),
  }));
}

/**
 * The charge amount always comes from the persisted order total.
 * Client-supplied amounts are ignored by construction.
 */
export function resolveOrderChargeAmount(orderTotal: number): number {
  const value = Math.round(Number(orderTotal) * 100) / 100;
  if (!value || value <= 0 || isNaN(value)) {
    throw new Error("Valor do pedido inválido");
  }
  return value;
}
