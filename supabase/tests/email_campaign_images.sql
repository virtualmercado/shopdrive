-- Controlled tests: all writes roll back, no confirmation/enqueue/SMTP calls.
BEGIN;
SELECT set_config('request.jwt.claim.sub', (SELECT user_id::text FROM public.user_roles WHERE role='admin' ORDER BY user_id LIMIT 1), true);
DO $$
DECLARE m public.media_files; c uuid; h text; original text; q bigint; s bigint; rejected boolean;
BEGIN
 SELECT * INTO m FROM public.media_files WHERE file_path ~ '^uploads/[A-Za-z0-9_-]+\.(jpg|jpeg|png|webp)$' AND mime_type IN ('image/jpeg','image/png','image/webp') AND size<=1572864 ORDER BY created_at DESC LIMIT 1;
 IF m.id IS NULL THEN RAISE EXCEPTION 'test_requires_existing_master_image'; END IF;
 SELECT count(*) INTO q FROM public.email_queue;
 SELECT count(*) INTO s FROM public.email_suppressions;
 c:=public.admin_save_email_campaign(NULL,'Image test','Subject','',NULL,NULL,'{}',NULL,NULL,NULL);
 IF (SELECT media_id FROM public.email_campaigns WHERE id=c) IS NOT NULL THEN RAISE EXCEPTION 'partial_no_image_failed'; END IF;
 PERFORM public.admin_save_email_campaign(c,'Image test','Subject','Complete message','Open','https://shopdrive.com.br','{}',m.id,'Alt <safe>','https://shopdrive.com.br');
 IF (SELECT image_url FROM public.email_campaigns WHERE id=c) IS DISTINCT FROM m.url THEN RAISE EXCEPTION 'canonical_url_failed'; END IF;
 h:=public.admin_preview_email_campaign('Subject','Complete message','Open','https://shopdrive.com.br',m.id,'Alt <safe>','https://shopdrive.com.br');
 IF h <> public.render_email_campaign_html('Subject','Complete message','Open','https://shopdrive.com.br','https://shopdrive.com.br/descadastro?token=PREVIEW_PREVIA_PREVIA_PREVIA123',m.id,'Alt <safe>','https://shopdrive.com.br') THEN RAISE EXCEPTION 'preview_renderer_diverged'; END IF;
 IF position('alt="Alt &lt;safe&gt;"' IN h)=0 OR position('height:auto' IN h)=0 OR position(m.url IN h)=0 OR position('Não quero receber comunicações comerciais' IN h)=0 THEN RAISE EXCEPTION 'image_html_failed'; END IF;
 IF public.campaign_master_asset_mutable(m.file_path) THEN RAISE EXCEPTION 'storage_retention_failed'; END IF;
 rejected:=false;
 BEGIN DELETE FROM public.media_files WHERE id=m.id; EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'metadata_delete_allowed'; END IF;
 rejected:=false;
 BEGIN UPDATE public.media_files SET file_path='uploads/replacement.jpg' WHERE id=m.id; EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'metadata_replace_allowed'; END IF;
 rejected:=false;
 BEGIN PERFORM public.admin_preview_email_campaign('Subject','Message',NULL,NULL,m.id,'Alt','javascript:alert(1)'); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'unsafe_link_allowed'; END IF;
 rejected:=false;
 BEGIN UPDATE public.email_campaigns SET media_id=NULL,image_url='https://arbitrary.example/image.jpg' WHERE id=c; EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'arbitrary_url_allowed'; END IF;
 UPDATE public.email_campaigns SET status='completed' WHERE id=c;
 rejected:=false;
 BEGIN UPDATE public.email_campaigns SET media_id=NULL,image_url=NULL WHERE id=c; EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'historical_image_mutated'; END IF;
 UPDATE public.email_campaigns SET status='draft' WHERE id=c;
 PERFORM public.admin_save_email_campaign(c,'Image test','Subject','Complete message',NULL,NULL,'{}',NULL,NULL,NULL);
 IF (SELECT image_url FROM public.email_campaigns WHERE id=c) IS NOT NULL THEN RAISE EXCEPTION 'remove_image_failed'; END IF;
 original:=public.admin_preview_email_campaign('Subject','Complete message',NULL,NULL);
 IF original <> public.admin_preview_email_campaign('Subject','Complete message',NULL,NULL,NULL,NULL,NULL) THEN RAISE EXCEPTION 'no_image_regression'; END IF;
 UPDATE public.media_files SET size=1572865 WHERE id=m.id;
 rejected:=false;
 BEGIN PERFORM public.admin_preview_email_campaign('Subject','Message',NULL,NULL,m.id,NULL,NULL); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'size_limit_failed'; END IF;
 UPDATE public.media_files SET size=m.size,mime_type='image/svg+xml' WHERE id=m.id;
 rejected:=false;
 BEGIN PERFORM public.admin_preview_email_campaign('Subject','Message',NULL,NULL,m.id,NULL,NULL); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'svg_allowed'; END IF;
 PERFORM set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000000',true);
 rejected:=false;
 BEGIN PERFORM public.admin_preview_email_campaign('Subject','Message',NULL,NULL,NULL,NULL,NULL); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'nonadmin_allowed'; END IF;
 IF q<>(SELECT count(*) FROM public.email_queue) OR s<>(SELECT count(*) FROM public.email_suppressions) THEN RAISE EXCEPTION 'queue_or_suppression_changed'; END IF;
 RAISE NOTICE 'Campaign image controlled tests passed; no enqueue/send executed.';
END $$;
ROLLBACK;